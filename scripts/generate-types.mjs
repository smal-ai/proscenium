import { readFile, writeFile, mkdir } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
const schema = JSON.parse(await readFile("docs/contracts/schema.json", "utf8"));
const properties = Object.fromEntries(Object.keys(schema.$defs).sort().map(name =>
  [name, { $ref: `#/$defs/${name}` }]));
const result = await compile({ type: "object", additionalProperties: false, properties,
  required: Object.keys(properties), $defs: schema.$defs }, "ContractDefinitions", {
  bannerComment: "", additionalProperties: false, declareExternallyReferenced: true,
  enableConstEnums: false, format: true, unknownAny: true,
});
await mkdir("apps/frontend/src/api/generated", { recursive: true });
const target = "apps/frontend/src/api/generated/contracts.ts";
const content = "// Generated by json-schema-to-typescript 15.0.4. Do not edit.\n" + result;
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8") !== content) throw new Error("Generated TypeScript contract drift");
} else {
  await writeFile(target, content);
}
