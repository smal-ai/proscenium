"""Deterministic Pydantic RootModel bindings preserving JSON's exact wire representation.

Validation is delegated to the normative schema, including conditional/closed unions,
not Pydantic coercion. Each generated class supports model_validate/model_dump/json.
"""

import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/contracts/schema.json"
TARGET = ROOT / "apps/backend/src/proscenium/contracts"


def generate() -> dict[Path, str]:
    source = SOURCE.read_text()
    names = sorted(json.loads(source)["$defs"])
    header = """# Generated by scripts/generate_contracts.py v1. Do not edit.
from typing import Any, ClassVar
from pydantic import RootModel, model_validator
from proscenium.contracts import SCHEMA, validate
from proscenium.api.errors import DomainError

class ContractModel(RootModel[Any]):
    definition: ClassVar[str]

    @model_validator(mode="before")
    @classmethod
    def check_schema(cls, value: Any) -> Any:
        if isinstance(value, cls):
            return value.root
        try:
            return validate(cls.definition, value)
        except DomainError as exc:
            raise ValueError(exc.message) from exc

    @classmethod
    def model_json_schema(cls, *args: Any, **kwargs: Any) -> dict[str, Any]:
        return {"$ref": f"#/$defs/{cls.definition}", "$defs": SCHEMA["$defs"]}

"""
    classes = "\n".join(f'class {n}(ContractModel):\n    definition = "{n}"\n' for n in names)
    api = yaml.safe_load((ROOT / "docs/contracts/openapi.yaml").read_text())
    operations = [
        "// Generated from OpenAPI by scripts/generate_contracts.py v1. Do not edit.",
        'import type * as C from "./contracts";',
        "export interface Operations {",
    ]
    routes = ["export const routes = {"]

    def resolve(value: dict) -> dict:
        while value.get("$ref", "").startswith("#/components/"):
            value = api["components"][value["$ref"].split("/")[2]][value["$ref"].split("/")[3]]
        return value

    def wire(value: dict, fallback: str) -> str:
        content = resolve(value).get("content", {})
        schema = resolve(content.get("application/json", {}).get("schema", {}))
        if "application/json" in content and not schema.get("$ref", "").startswith(
            "./schema.json#/$defs/"
        ):
            raise ValueError("JSON envelopes must reference a normative definition")
        return "C." + schema["$ref"].split("/")[-1] if "$ref" in schema else fallback

    def query_wire(schema: dict) -> str:
        if schema.get("type") == "integer":
            return "number"
        if schema.get("type") == "boolean":
            return "boolean"
        if schema.get("type") != "string":
            raise ValueError("Query parameters require integer, boolean or string schemas")
        if "enum" in schema:
            return " | ".join(json.dumps(value) for value in schema["enum"])
        return "string"

    for path, methods in api["paths"].items():
        for method, operation in methods.items():
            if not isinstance(operation, dict) or "operationId" not in operation:
                continue
            name = operation["operationId"]
            parameters = [
                resolve(p) for p in methods.get("parameters", []) + operation.get("parameters", [])
            ]
            params = [p for p in parameters if p["in"] == "path"]
            queries = [p for p in parameters if p["in"] == "query"]
            path_type = (
                "{ " + "; ".join(p["name"] + ": string" for p in params) + " }"
                if params
                else "Record<string, never>"
            )
            query_type = (
                "{ "
                + "; ".join(p["name"] + "?: " + query_wire(p["schema"]) for p in queries)
                + " }"
                if queries
                else "Record<string, never>"
            )
            body = wire(
                operation.get("requestBody", {}), "Blob" if "requestBody" in operation else "never"
            )
            responses = [
                wire(v, "ArrayBuffer")
                for k, v in operation["responses"].items()
                if str(k).startswith("2")
            ]
            response = responses[0] if responses else "never"
            operations.append(
                f"  {name}: {{ body: {body}; response: {response}; path: {path_type}; query: {query_type} }};"
            )
            routes.append(
                f'  {name}: {{ method: "{method.upper()}", path: "{path}", binary: {str(response == "ArrayBuffer").lower()} }},'
            )
    operations += ["}", *routes, "} as const;", ""]
    return {
        TARGET / "schema.json": source,
        TARGET / "generated.py": header + classes,
        TARGET / "transitions.json": (ROOT / "docs/contracts/state-transitions.json").read_text(),
        TARGET / "source.sha256": hashlib.sha256(source.encode()).hexdigest() + "\n",
        ROOT / "apps/frontend/src/api/generated/operations.ts": "\n".join(operations),
    }


if __name__ == "__main__":
    import sys

    for path, content in generate().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated contract drift: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
