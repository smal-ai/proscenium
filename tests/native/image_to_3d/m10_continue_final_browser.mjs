async function observeDecisions(){
  const pending=rows('decisions').filter(d=>d.work_id===work&&d.state==='pending');
  for(const decision of pending){
    if(!result.permission_decisions_reported.includes(decision.decision_id)){
      result.permission_decisions_reported.push(decision.decision_id);
      result.exact_pending_decision=decision;
      await fs.writeFile(`${root}/unexpected-decision.private.json`,JSON.stringify(decision,null,2));
      console.log(JSON.stringify({event:'COORDINATOR_DECISION_REQUIRED',decision}));await save();
    }
    // This file is NEVER generated by the harness or native model. It is an optional
    // bridge for an exact, explicit coordinator answer received in the supervising chat.
    try{
      const approval=JSON.parse(await fs.readFile(`${root}/coordinator-answer.json`,'utf8'));
      if(approval.source!=='coordinator-explicit-message'||approval.decision_id!==decision.decision_id||approval.fingerprint!==decision.fingerprint)
        throw new Error('Coordinator answer does not bind this exact decision');
      if(!['approve_once','decline'].includes(approval.action))throw new Error('No broader permission or budget answer is supported');
      const body={schema_version:'1.0',operation_id:approval.operation_id,project_id:project,
        expected_revision:decision.state_revision,fingerprint:decision.fingerprint,action:approval.action};
      result.coordinator_answer_receipt=await page.evaluate(async({body,csrf,path})=>{
        const r=await fetch(path,{method:'POST',credentials:'same-origin',headers:{'Content-Type':'application/json','Idempotency-Key':body.operation_id,'X-CSRF-Token':csrf},body:JSON.stringify(body)});
        return {status:r.status,body:await r.json()};
      },{body,csrf,path:`${prefix}/decisions/${decision.decision_id}/answer`});
      await fs.rename(`${root}/coordinator-answer.json`,`${root}/coordinator-answer-applied.private.json`);await save();
    }catch(error){if(error.code!=='ENOENT')throw error;}
  }
}
async function resume(mode){
  await page.getByLabel('Resume mode').selectOption(mode);
  if(mode==='continue_work')await page.getByLabel('Original work to continue').selectOption(work);
  const responsePromise=page.waitForResponse(r=>r.request().method()==='POST'&&new URL(r.url()).pathname===`${prefix}/resume`);
  await page.getByRole('button',{name:'Resume',exact:true}).click();
  const response=await responsePromise;
  return {status:response.status(),command:response.request().postDataJSON(),receipt:await response.json()};
}
