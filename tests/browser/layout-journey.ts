import { expect, type Page } from "@playwright/test";
import { StudioFixture } from "./studio-fixture";

export async function verifyLayout(page: Page, origin: string, dpr: number) {
  const studio = new StudioFixture(page, origin);
  await studio.install({ savedLayout: true });
  await studio.open(); await studio.ready();
  expect(await page.evaluate(() => devicePixelRatio)).toBe(dpr);
  const navigator = page.getByRole("complementary", { name: "Navigator", exact: true });
  const assistant = page.getByRole("complementary", { name: "Assistant panel" });
  const width = async (locator: typeof navigator) => (await locator.boundingBox())!.width;
  await expect.poll(() => width(navigator)).toBe(280);
  await expect.poll(() => width(assistant)).toBe(400);
  const left = page.getByRole("separator", { name: "Resize Navigator" });
  const right = page.getByRole("separator", { name: "Resize Assistant" });
  await left.focus(); await page.keyboard.press("ArrowRight");
  await expect.poll(() => width(navigator)).toBe(296);
  await left.press("ArrowLeft");
  const leftBox = (await left.boundingBox())!;
  await page.mouse.move(leftBox.x + leftBox.width / 2, leftBox.y + 150);
  await page.mouse.down(); await page.mouse.move(leftBox.x + leftBox.width / 2 + 64, leftBox.y + 150); await page.mouse.up();
  await expect.poll(() => width(navigator)).toBe(344);
  const navigatorRemembered = await width(navigator);
  await right.focus(); await right.press("ArrowLeft");
  await expect.poll(() => width(assistant)).toBe(416);
  await right.press("ArrowRight");
  await expect.poll(() => width(assistant)).toBe(400);
  const box = (await right.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + 150);
  await page.mouse.down(); await page.mouse.move(box.x - 80, box.y + 150); await page.mouse.up();
  const remembered = await width(assistant);
  expect(remembered).toBeGreaterThan(470);
  await page.getByRole("button", { name: "Outliner", exact: true }).click();
  await page.getByRole("button", { name: "Critic", exact: true }).click();
  await page.getByRole("button", { name: "Collapse Navigator" }).click();
  await expect.poll(() => width(navigator)).toBe(52);
  await page.getByRole("button", { name: "Expand Navigator" }).click();
  await expect.poll(() => width(navigator)).toBe(navigatorRemembered);
  await page.getByRole("button", { name: "Collapse Assistant" }).click();
  await expect.poll(() => width(assistant)).toBe(52);
  await page.getByRole("button", { name: "Expand Assistant" }).click();
  await expect.poll(() => width(assistant)).toBe(remembered);
  await expect.poll(() => width(navigator)).toBe(navigatorRemembered);
  await page.getByRole("button", { name: "Chat focus", exact: true }).click();
  await expect(page.locator("main.review-panel")).toBeHidden();
  await page.getByRole("button", { name: "Restore split view" }).click();
  await expect.poll(() => width(assistant)).toBe(remembered);
  await expect(page.getByRole("button", { name: "Outliner", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("button", { name: "Critic", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "Copilot", exact: true }).click();
  for (let i = 0; i < 40; i++) studio.emit("assistant.completed", { message_id: `message-${i}`, text: `Synthetic message ${i}. ${"Long paragraph. ".repeat(20)}`, native_agent_id: null });
  const scroll = page.locator(".chat-scroll");
  const atBottom = () => scroll.evaluate(e => e.scrollHeight - e.scrollTop - e.clientHeight);
  await expect.poll(atBottom).toBeLessThan(4);
  await scroll.evaluate(e => { e.scrollTop = 0; e.dispatchEvent(new Event("scroll")); });
  await expect(page.getByRole("button", { name: "Jump to latest" })).toBeVisible();
  studio.emit("assistant.completed", { message_id: "latest", text: "Latest message", native_agent_id: null });
  await page.getByRole("button", { name: "Chat focus", exact: true }).click();
  await page.getByRole("button", { name: "Collapse Navigator" }).click();
  await page.getByRole("button", { name: "Expand Navigator" }).click();
  await page.getByRole("button", { name: "Restore split view" }).click();
  await expect(page.getByRole("button", { name: "Jump to latest" })).toBeVisible();
  expect(await scroll.evaluate(e => e.scrollTop)).toBeLessThan(100);
  await page.getByRole("button", { name: "Jump to latest" }).click();
  await expect.poll(atBottom).toBeLessThan(4);
  await page.getByRole("button", { name: "Collapse Assistant" }).click();
  await page.getByRole("button", { name: "Expand Assistant" }).click();
  await expect.poll(atBottom).toBeLessThan(4);
  expect(studio.submissions).toEqual([]);
  studio.assertHermetic();
}
